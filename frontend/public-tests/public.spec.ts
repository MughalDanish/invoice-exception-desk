import { test, expect } from "@playwright/test";
test("anonymous synthetic demo is readable, immutable, and useful on mobile", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await expect(page.getByText("Read-only synthetic demonstration", { exact: false })).toBeVisible();
  await expect(page.locator("tbody tr")).toHaveCount(15);
  await expect(page.getByRole("button", { name: "Upload invoice" })).toHaveCount(0);
  await expect(page.getByRole("textbox", { name: "Password", exact: true })).toHaveCount(0);
  await page.screenshot({ path: "../docs/screenshots/public-overview.png", fullPage: true });
  await page.getByRole("link", { name: "Exception queue", exact: true }).first().click();
  await page.getByLabel("Issue type").selectOption("TOTAL_MISMATCH");
  await expect(page.locator("tbody tr")).toHaveCount(1);
  await page.locator("tbody tr").getByRole("link", { name: "Review" }).click();
  await expect(page.getByLabel("Total", { exact: true })).toBeDisabled();
  await expect(page.getByTitle("Original invoice PDF")).toBeVisible();
  await expect(page.getByRole("button", { name: "Post to ledger" })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Approve current revision" })).toHaveCount(0);
  await page.screenshot({ path: "../docs/screenshots/total-mismatch.png", fullPage: true });
  await page.getByRole("tab", { name: "Audit history" }).click();
  await expect(page.getByRole("heading", { name: "Every action, accounted for" })).toBeVisible();
  await page.screenshot({ path: "../docs/screenshots/audit.png", fullPage: true });
  await page.getByRole("link", { name: "Suppliers", exact: true }).click();
  await expect(page.getByRole("button", { name: "Register supplier" })).toHaveCount(0);
  await page.getByRole("link", { name: "Ledger", exact: true }).click();
  await expect(page.locator("tbody tr")).toHaveCount(1);
  await expect(page.getByRole("button", { name: "Export CSV" })).toHaveCount(0);
  const denied = await page.request.post("http://127.0.0.1:8002/api/v1/vendors", { data: { display_name: "attacker" } });
  expect(denied.status()).toBe(403);
  await page.getByRole("link", { name: "Overview", exact: true }).click();
  await expect(page.locator("tbody tr")).toHaveCount(15);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "../docs/screenshots/public-mobile.png", fullPage: true });
  expect(errors).toEqual([]);
});
